const ExcelJS = require("exceljs");

async function generateExcel(sections, meta, filePath) {
  const wb = new ExcelJS.Workbook();
  wb.creator = "EcoTrack";
  wb.created = new Date();

  const info = wb.addWorksheet("Overview");
  info.columns = [{ width: 22 }, { width: 40 }];
  info.addRow(["EcoTrack Platform Report"]).font = { bold: true, size: 14 };
  info.addRow(["Period", `${meta.fromLabel} to ${meta.toLabel}`]);
  info.addRow(["Generated", meta.generatedLabel]);
  if (meta.generatedBy) info.addRow(["Generated by", meta.generatedBy]);
  info.addRow(["Sheets", sections.map((s) => s.title).join(", ")]);

  sections.forEach((s) => {
    const ws = wb.addWorksheet(s.title.slice(0, 31));
    ws.columns = s.columns.map((c) => ({
      header: c.header,
      key: c.key,
      width: Math.max(c.header.length + 4, 16),
    }));
    s.rows.forEach((r) => ws.addRow(r));

    const head = ws.getRow(1);
    head.font = { bold: true, color: { argb: "FFFFFFFF" } };
    head.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: "FF0F172A" },
    };
    ws.views = [{ state: "frozen", ySplit: 1 }];
    if (!s.rows.length) ws.addRow(["No data for this period."]);
  });

  await wb.xlsx.writeFile(filePath);
}

module.exports = { generateExcel };
